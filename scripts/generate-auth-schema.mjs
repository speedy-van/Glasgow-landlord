import { writeFile } from "node:fs/promises";
import { getMigrations } from "better-auth/db/migration";
import { authOptions } from "../lib/auth-options.ts";
import { postgresTestPool } from "../tests/helpers/postgres.mjs";

const pool = await postgresTestPool();
try {
  const migration = await getMigrations(
    authOptions({
      database: pool,
      secret: "schema-generation-only-never-a-runtime-secret",
      origin: "http://localhost:3000",
      administrators: ["schema@example.invalid"],
    }),
  );
  const ddl = await migration.compileMigrations();
  await writeFile(
    new URL("../sql/002-admin.sql", import.meta.url),
    "-- Generated by better-auth 1.7.12 from lib/auth-options.ts.\n" +
      ddl +
      "\n",
  );
  console.log(
    "Generated the administrator schema from the installed authentication library.",
  );
} finally {
  await pool.end();
}
